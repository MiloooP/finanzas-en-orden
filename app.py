def database_url() -> str:
    value = os.getenv("FINANZAS_DATABASE_URL", "").strip()
    if not value:
        try:
            value = str(st.secrets.get("FINANZAS_DATABASE_URL", "")).strip()
        except Exception:
            value = ""
    return value


class CloudConnection:
    """Small adapter for qmark placeholders on the PostgreSQL connection."""
    def __init__(self, raw):
        self.raw = raw
        self.postgres = True

    def execute(self, sql: str, params=()):
        return self.raw.execute(sql.replace("?", "%s"), params)

    def executescript(self, sql: str):
        for statement in sql.split(";"):
            if statement.strip():
                self.raw.execute(statement)

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        try:
            if exc_type:
                self.raw.rollback()
            else:
                self.raw.commit()
        finally:
            self.raw.close()


def connect() -> CloudConnection:
    url = database_url()
    if not url:
        raise RuntimeError(
            "Falta configurar FINANZAS_DATABASE_URL en Streamlit Secrets. "
            "La versión publicada necesita PostgreSQL para guardar tus datos."
        )
    import psycopg
    from psycopg.rows import dict_row
    raw = psycopg.connect(url, row_factory=dict_row, connect_timeout=15)
    return CloudConnection(raw)


def is_duplicate_error(error: Exception) -> bool:
    return getattr(error, "sqlstate", None) == "23505"


def init_db() -> None:
    with connect() as con:
        con.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL,
            full_name TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_uq ON users (LOWER(username));
        CREATE TABLE IF NOT EXISTS accounts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            name TEXT NOT NULL,
            kind TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(user_id, name)
        );
        CREATE TABLE IF NOT EXISTS categories (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            name TEXT NOT NULL,
            kind TEXT NOT NULL CHECK(kind IN ('Ingreso','Gasto')),
            UNIQUE(user_id, name, kind)
        );
        CREATE TABLE IF NOT EXISTS transactions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
            category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
            kind TEXT NOT NULL CHECK(kind IN ('Ingreso','Gasto')),
            amount_cents BIGINT NOT NULL CHECK(amount_cents > 0),
            movement_date TEXT NOT NULL,
            description TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS idx_transactions_user_date ON transactions(user_id, movement_date);
        """)

def password_digest(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    derived = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 310_000)
    return f"pbkdf2_sha256${salt.hex()}${derived.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        _, salt_hex, digest_hex = stored.split("$")
        return hmac.compare_digest(password_digest(password, bytes.fromhex(salt_hex)).split("$")[2], digest_hex)
    except (ValueError, TypeError):
        return False


def create_user(username: str, full_name: str, password: str) -> tuple[bool, str]:
    try:
        with connect() as con:
            con.execute("INSERT INTO users(username,full_name,password_hash) VALUES(?,?,?)",
                        (username.strip(), full_name.strip(), password_digest(password)))
        return True, "Cuenta creada. Ya puedes iniciar sesión."
    except Exception as exc:
        if is_duplicate_error(exc):
            return False, "Ese nombre de usuario ya existe. Elige otro."
        raise


def money(cents: int | float) -> str:
    value = int(round(float(cents) / 100))
    return f"$ {value:,.0f}".replace(",", ".") + " COP"


def get_accounts(user_id: int) -> list[dict]:
    with connect() as con:
        return [dict(row) for row in con.execute("SELECT id,name,kind FROM accounts WHERE user_id=? ORDER BY name", (user_id,)).fetchall()]


def get_categories(user_id: int, kind: str | None = None) -> list[dict]:
    with connect() as con:
        if kind:
            return [dict(row) for row in con.execute("SELECT id,name,kind FROM categories WHERE user_id=? AND kind=? ORDER BY name", (user_id, kind)).fetchall()]
        return [dict(row) for row in con.execute("SELECT id,name,kind FROM categories WHERE user_id=? ORDER BY kind,name", (user_id,)).fetchall()]


def load_transactions(user_id: int, start: date | None = None, end: date | None = None,
                      account_id: int | None = None, category_id: int | None = None) -> pd.DataFrame:
    sql = """SELECT t.id,t.kind,t.amount_cents/100.0 AS amount,t.movement_date AS fecha,
                    c.name AS categoria,a.name AS cuenta,t.description AS descripcion
             FROM transactions t JOIN categories c ON c.id=t.category_id
             JOIN accounts a ON a.id=t.account_id WHERE t.user_id=?"""
    params: list[object] = [user_id]
    if start:
        sql += " AND t.movement_date>=?"; params.append(start.isoformat())
    if end:
        sql += " AND t.movement_date<=?"; params.append(end.isoformat())
    if account_id:
        sql += " AND t.account_id=?"; params.append(account_id)
    if category_id:
        sql += " AND t.category_id=?"; params.append(category_id)
    sql += " ORDER BY t.movement_date DESC,t.id DESC"
    with connect() as con:
        rows = con.execute(sql, params).fetchall()
    frame = pd.DataFrame([dict(r) for r in rows])
    if not frame.empty:
        frame["amount"] = pd.to_numeric(frame["amount"], errors="coerce").astype(float)
    return frame


def add_account(user_id: int, name: str, kind: str) -> tuple[bool, str]:
    try:
        with connect() as con:
            con.execute("INSERT INTO accounts(user_id,name,kind) VALUES(?,?,?)", (user_id, name.strip(), kind))
        return True, "Cuenta guardada."
    except Exception as exc:
        if is_duplicate_error(exc):
            return False, "Ya tienes una cuenta con ese nombre."
        raise


def add_category(user_id: int, name: str, kind: str) -> tuple[bool, str]:
    try:
        with connect() as con:
            con.execute("INSERT INTO categories(user_id,name,kind) VALUES(?,?,?)", (user_id, name.strip(), kind))
        return True, "Categoría guardada."
    except Exception as exc:
        if is_duplicate_error(exc):
            return False, "Ya tienes esa categoría para ese tipo."
        raise


def add_transaction(user_id: int, account_id: int, category_id: int, kind: str,
                    amount_cents: int, movement_date: date, description: str) -> None:
    with connect() as con:
        # Ownership checks keep IDs from another user's account/category from being used.
        valid = con.execute("""SELECT 1 FROM accounts a JOIN categories c ON c.user_id=a.user_id
                            WHERE a.id=? AND c.id=? AND a.user_id=? AND c.kind=?""",
                            (account_id, category_id, user_id, kind)).fetchone()
        if not valid:
            raise ValueError("La cuenta o categoría seleccionada no pertenece a tu usuario.")
        con.execute("""INSERT INTO transactions(user_id,account_id,category_id,kind,amount_cents,movement_date,description)
                     VALUES(?,?,?,?,?,?,?)""", (user_id, account_id, category_id, kind, amount_cents,
                                                movement_date.isoformat(), description.strip()))


def delete_transaction(user_id: int, tx_id: int) -> None:
    with connect() as con:
        con.execute("DELETE FROM transactions WHERE id=? AND user_id=?", (tx_id, user_id))


def update_transaction(user_id: int, tx_id: int, account_id: int, category_id: int, kind: str,
                       amount_cents: int, movement_date: date, description: str) -> None:
    with connect() as con:
        valid = con.execute("""SELECT 1 FROM accounts a JOIN categories c ON c.user_id=a.user_id
                            WHERE a.id=? AND c.id=? AND a.user_id=? AND c.kind=?""",
                            (account_id, category_id, user_id, kind)).fetchone()
        if not valid:
            raise ValueError("La cuenta o categoría seleccionada no pertenece a tu usuario.")
        con.execute("""UPDATE transactions SET account_id=?,category_id=?,kind=?,amount_cents=?,movement_date=?,description=?
                     WHERE id=? AND user_id=?""", (account_id, category_id, kind, amount_cents,
                                                     movement_date.isoformat(), description.strip(), tx_id, user_id))


def delete_category(user_id: int, category_id: int) -> tuple[bool, str]:
    with connect() as con:
        used = con.execute("SELECT 1 FROM transactions WHERE category_id=? AND user_id=? LIMIT 1", (category_id, user_id)).fetchone()
        if used:
            return False, "No puedes borrar una categoría que ya tiene movimientos."
        con.execute("DELETE FROM categories WHERE id=? AND user_id=?", (category_id, user_id))
    return True, "Categoría eliminada."


def delete_account(user_id: int, account_id: int) -> tuple[bool, str]:
    with connect() as con:
        used = con.execute("SELECT 1 FROM transactions WHERE account_id=? AND user_id=? LIMIT 1", (account_id, user_id)).fetchone()
        if used:
            return False, "No puedes borrar una cuenta que ya tiene movimientos."
        con.execute("DELETE FROM accounts WHERE id=? AND user_id=?", (account_id, user_id))
    return True, "Cuenta eliminada."


